#!/usr/bin/env python3
"""Generate RESULTS.md for experiment 3.

Reports are generated, never hand-written: everything here is derived from
an append-only trajectory file, and hand edits are reverted on the next run.

    python experiments/agent-checkpoint/ckpt_report.py --results <file.jsonl> [--level 99|95]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import ckpt_hypotheses as ch  # noqa: E402
import ckpt_metrics as cm  # noqa: E402


def fmt(d: dict | None) -> str:
    if d is None or d.get("value") is None:
        return "n/a (n=0)"
    return f"{d['value']*100:.1f}% [{d['ci_low']*100:.1f}, {d['ci_high']*100:.1f}] ({d['k']}/{d['n']})"


def money(x: float | None, digits: int = 4) -> str:
    return "n/a" if x is None else f"${x:.{digits}f}"


def avoided(b: dict) -> str:
    """Extra spend per silent failure removed. A mode that removes failures
    while costing no more than the baseline has nothing to divide."""
    v = b["cost_per_avoided_silent_failure_usd"]
    if v is None:
        return "n/a (none avoided)"
    if v <= 0:
        return "$0 (no extra spend)"
    return money(v, 4)


def results_markdown(s: dict, results, source: str, level: str, stage: int | None) -> str:
    md = [
        f"# Results — agent-checkpoint, stage {stage if stage is not None else '?'}",
        "",
        f"Generated by `ckpt_report.py` from `{source}`. Do not edit by hand.",
        "",
        f"{s['n_trajectories']} trajectories · requested `{', '.join(s['models_requested'])}` · "
        f"served `{', '.join(s['models_resolved'])}` · ${s['total_cost_usd']:.4f} · "
        "brackets are Wilson 95% intervals.",
        "",
        "## By mode",
        "",
        "| Mode | n | fired | outcome pass (fired) | **silent failure** | false green (conditional) | detection (T7 excl.) | mean steps | cost / trajectory | multiplier |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for m in s["modes_present"]:
        b = s["by_mode"][m]
        mult = "1.00x" if m == cm.BASELINE else (f"{b['cost_multiplier']:.2f}x" if b["cost_multiplier"] else "n/a")
        md.append(
            f"| `{m}` | {b['n']} | {b['n_fired'] if b['n_fired'] is not None else '–'} | "
            f"{fmt(b['outcome_pass_rate_fired']) if m != 'clean' else fmt(b['outcome_pass_rate'])} | "
            f"**{fmt(b['silent_failure_rate'])}** | {fmt(b['false_green_rate'])} | "
            f"{fmt(b['detection_rate'])} | {b['mean_steps']} | {money(b['mean_cost_usd'])} | {mult} |"
        )
    md += [
        "",
        "Silent failure: the injection fired, the outcome is wrong, and the agent claimed "
        "success. Per fired injection, T7 included. The conditional false-green rate is "
        "experiment 2's definition, over every trajectory of the mode that finished wrong.",
        "",
        "## Reconcile, when it is optional",
        "",
        "| Metric | value |",
        "|---|---|",
        f"| reconcile usage rate (`inject_tool`, any call) | {fmt(s['reconcile_usage_rate'])} |",
        f"| reconcile on the corrupted subject (fired `inject_tool`) | {fmt(s['reconcile_on_subject_rate'])} |",
        "",
        "## Contamination depth (tool-call steps until an agent-initiated recheck, else end)",
        "",
        "| Mode | n | median | range | distribution |",
        "|---|---|---|---|---|",
    ]
    for m in s["modes_present"]:
        if m == "clean":
            continue
        c = s["by_mode"][m]["contamination"]
        rng = f"{c['min']}–{c['max']}" if c["n"] else "–"
        md.append(f"| `{m}` | {c['n']} | {c['median']} | {rng} | `{c['distribution']}` |")
    md += [
        "",
        "For `inject_enforced` the depth is reported, not interpreted: the definition rests "
        "on an agent-initiated recheck, which the enforced checkpoint makes unnecessary.",
        "",
        "## Cost accounting",
        "",
        "| Mode | total | per trajectory | per correct outcome | per avoided silent failure |",
        "|---|---|---|---|---|",
    ]
    for m in s["modes_present"]:
        b = s["by_mode"][m]
        md.append(f"| `{m}` | {money(b['cost_usd'])} | {money(b['mean_cost_usd'], 5)} | "
                  f"{money(b['cost_per_correct_usd'], 5)} | "
                  f"{avoided(b) if m in ('inject_tool', 'inject_enforced') else '–'} |")
    md += [
        "",
        "Per avoided silent failure: (mean cost of the mode − mean cost of `inject`) / "
        "(silent failure rate of `inject` − rate of the mode). n/a when nothing was avoided.",
        "",
        "## Harness health",
        "",
        "| Metric | value |",
        "|---|---|",
        f"| injection never fired | {fmt(s['injection_not_applicable_rate'])} |",
        f"| hit the step cap | {fmt(s['step_cap_rate'])} |",
        f"| truncated completion | {fmt(s['truncation_rate'])} |",
        f"| cells whose repeats differ (temperature 0) | {fmt(s['variation']['rate'])} |",
        "",
        "## Hypotheses",
        "",
        ch.to_markdown(results, level),
        "",
        "## Per task",
        "",
        "| Task | n | outcome pass | silent: inject | silent: inject_tool | silent: inject_enforced | control |",
        "|---|---|---|---|---|---|---|",
    ]
    for tid, t in s["per_task"].items():
        sf = t["silent_failure_by_mode"]
        md.append(f"| {tid} | {t['n']} | {fmt(t['outcome_pass'])} | {fmt(sf.get('inject'))} | "
                  f"{fmt(sf.get('inject_tool'))} | {fmt(sf.get('inject_enforced'))} | "
                  f"{'yes' if t['is_confound_control'] else ''} |")
    return "\n".join(md) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", required=True)
    ap.add_argument("--out", default=str(HERE / "RESULTS.md"))
    ap.add_argument("--level", default="99", choices=["99", "95"],
                    help="interim look is 99 per the pre-registered stopping rule")
    args = ap.parse_args(argv)

    records = cm.load(args.results)
    if not records:
        print(f"no trajectories in {args.results}", file=sys.stderr)
        return 1
    summary = cm.summarize(records)
    results = ch.evaluate(records, level=args.level)
    stage = records[0].get("stage")
    Path(args.out).write_text(
        results_markdown(summary, results, Path(args.results).name, args.level, stage)
    )
    print(f"table -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
