#!/usr/bin/env python3
"""Generate RESULTS.md for the agent-trajectory experiment.

Reports are generated, never hand-written: everything here is derived from an
append-only trajectory file, and hand edits are reverted on the next run.

    python experiments/agent-verifier-gap/report_agent.py --results <file.jsonl>
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
for _p in (HERE, HERE.parent / "verifier-gap"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

import traj_hypotheses as th  # noqa: E402
import traj_metrics as tm  # noqa: E402


def fmt(d: dict) -> str:
    if d is None or d.get("value") is None:
        return "n/a (n=0)"
    return f"{d['value']*100:.1f}% [{d['ci_low']*100:.1f}, {d['ci_high']*100:.1f}] ({d['k']}/{d['n']})"


def results_markdown(summary: dict, results, source: str, level: str) -> str:
    s = summary
    md = [
        f"# Results — agent-verifier-gap, stage 1",
        "",
        f"Generated by `report_agent.py` from `{source}`. Do not edit by hand.",
        "",
        f"{s['n_trajectories']} trajectories · model `{', '.join(s['models_resolved'])}` ·",
        f"${s['total_cost_usd']:.4f} · brackets are Wilson 95% intervals.",
        "",
        "## Outcome by mode",
        "",
        "| Mode | n | outcome pass | mean steps | cost |",
        "|---|---|---|---|---|",
    ]
    for m in s["modes_present"]:
        b = s["by_mode"][m]
        md.append(f"| `{m}` | {b['n']} | {fmt(b['outcome_pass_rate'])} | "
                  f"{b['mean_steps']} | ${b['cost_usd']:.4f} |")
    c = s["contamination"]
    md += [
        "",
        "## Headline",
        "",
        "| Metric | value |",
        "|---|---|",
        f"| **trajectory false-green rate** | **{fmt(s['trajectory_false_green_rate'])}** |",
        f"| detection rate (T7 excluded) | {fmt(s['detection_rate'])} |",
        f"| detection rate (T7 included) | {fmt(s['detection_rate_with_control'])} |",
        f"| recovery rate | {fmt(s['recovery_rate'])} |",
        f"| Δdetection (verify − plain) | {s['delta_detection_pp']:+.1f} pp |",
        f"| cost multiplier (verify / plain) | {s['cost_multiplier']:.2f}x |",
        "",
        f"Contamination depth, in tool-call steps: median **{c['median']}**, "
        f"range {c['min']}–{c['max']}, distribution `{c['distribution']}`.",
        "",
        "## Harness health",
        "",
        "| Metric | value |",
        "|---|---|",
        f"| injection never fired | {fmt(s['injection_not_applicable_rate'])} |",
        f"| hit the step cap | {fmt(s['step_cap_rate'])} |",
        "",
        "The first of these is high and it matters: the effective denominator is "
        f"{s['detection_rate']['n']}, not the 64 the matrix planned. See "
        "CALIBRATION.md stage 1.",
        "",
        "## Hypotheses",
        "",
        th.to_markdown(results, level),
        "",
        "## Per task",
        "",
        "| Task | n | outcome pass | detected | false green | control |",
        "|---|---|---|---|---|---|",
    ]
    for tid, t in s["per_task"].items():
        md.append(f"| {tid} | {t['n']} | {fmt(t['outcome_pass'])} | {fmt(t['detected'])} | "
                  f"{fmt(t['false_green'])} | {'yes' if t['is_confound_control'] else ''} |")
    return "\n".join(md) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", required=True)
    ap.add_argument("--out", default=str(HERE / "RESULTS.md"))
    ap.add_argument("--level", default="99", choices=["99", "95"],
                    help="interim look is 99 per the pre-registered stopping rule")
    args = ap.parse_args(argv)

    records = tm.load(args.results)
    if not records:
        print(f"no trajectories in {args.results}", file=sys.stderr)
        return 1
    summary = tm.summarize(records)
    results = th.evaluate(records, level=args.level)
    Path(args.out).write_text(
        results_markdown(summary, results, Path(args.results).name, args.level)
    )
    print(f"table -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
